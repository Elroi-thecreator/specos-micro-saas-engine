export type JobStatus = 'QUEUED' | 'PROCESSING' | 'COMPLETED' | 'FAILED';

export interface AgentJob {
  id: string;
  tenantSlug: string;
  moduleKey: 'docIntel' | 'supportSwarm' | 'codeAudit';
  status: JobStatus;
  inputPayload: any;
  resultPayload: any;
  tokensUsed: number;
  latencyMs: number;
  createdAt: string;
  completedAt?: string;
}

class AgentQueueService {
  private jobs: Map<string, AgentJob> = new Map();

  public enqueueJob(
    tenantSlug: string,
    moduleKey: 'docIntel' | 'supportSwarm' | 'codeAudit',
    inputPayload: any
  ): AgentJob {
    const jobId = `job_${Date.now()}_${Math.random().toString(36).substring(7)}`;
    const job: AgentJob = {
      id: jobId,
      tenantSlug,
      moduleKey,
      status: 'QUEUED',
      inputPayload,
      resultPayload: null,
      tokensUsed: 0,
      latencyMs: 0,
      createdAt: new Date().toISOString(),
    };

    this.jobs.set(jobId, job);

    // Simulate async distributed worker pick-up
    setTimeout(() => {
      this.processJob(jobId);
    }, 200);

    return job;
  }

  private processJob(jobId: string) {
    const job = this.jobs.get(jobId);
    if (!job) return;

    job.status = 'PROCESSING';
    const startTime = Date.now();

    // Execute based on module
    setTimeout(() => {
      let result = null;
      let tokens = 120;

      switch (job.moduleKey) {
        case 'docIntel':
          result = {
            riskLevel: 'High',
            flaggedClauses: 3,
            summary: 'Indemnity and liability clauses audited successfully by Kiro Contract Agent.',
          };
          tokens = 450;
          break;
        case 'supportSwarm':
          result = {
            sentiment: 'Urgent',
            confidence: 0.984,
            draftReply: 'Localized response generated by Kiro Support Swarm.',
          };
          tokens = 280;
          break;
        case 'codeAudit':
          result = {
            score: 96,
            violations: 0,
            status: 'Compliant with ARCH-001 and ARCH-002',
          };
          tokens = 620;
          break;
      }

      job.status = 'COMPLETED';
      job.resultPayload = result;
      job.tokensUsed = tokens;
      job.latencyMs = Date.now() - startTime;
      job.completedAt = new Date().toISOString();
    }, 800);
  }

  public getJob(jobId: string): AgentJob | null {
    return this.jobs.get(jobId) || null;
  }

  public listJobsForTenant(tenantSlug: string): AgentJob[] {
    return Array.from(this.jobs.values()).filter((j) => j.tenantSlug === tenantSlug);
  }
}

export const agentQueueService = new AgentQueueService();
